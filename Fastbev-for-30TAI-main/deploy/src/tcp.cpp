/*
 * tcp_icraft_runtime.cpp
 *
 * Board-side TCP1 runtime for the TCP CARLA model on Icraft XRT / ZG330.
 *
 * Data flow:
 *   PC TCP stream
 *     -> uint32_be packet_size + TCP1 packet
 *     -> tcp1_parse_frame()
 *     -> JPEG decode (libjpeg-turbo, RGB)
 *     -> ImageNet normalize, FP32 NHWC [1,256,900,3]
 *     -> state FP32 [1,9]
 *     -> Icraft Session::forward({rgb, state})
 *     -> pred_wp [1,4,2], mu_branches [1,2], sigma_branches [1,2]
 *     -> existing tcp_postprocess() (Beta + PID + fusion)
 *     -> TCP1 result -> PC
 *
 * This file is a self-contained board runtime: TCP1 protocol handling,
 * preprocessing, Icraft inference and control postprocessing are all here.
 *
 * Expected project-side dependencies:
 *   icraft_utils.hpp              (same helper used by the previous FastBEV runtime)
 *
 * TCP1 protocol parsing, CRC, ImageNet preprocessing and Beta/PID/fusion
 * postprocessing are intentionally embedded in this single source file.
 *   libturbojpeg
 *   Icraft XRT / ZG330Backend / HostBackend
 *
 * Model files:
 *   Use the JSON + RAW generated by Icraft.
 *
 * Example:
 * Default model paths:
 *   ./imodel/tcp/tcp_ZG.json
 *   ./imodel/tcp/tcp_ZG.raw
 *
 * Example:
 *   ./tcp_icraft_runtime \
 *       --device 'axi://zg330aiu?npu=0x40000000&dma=0x80000000' \
 *       --bind 0.0.0.0 \
 *       --port 5200
 */

