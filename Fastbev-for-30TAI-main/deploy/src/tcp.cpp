constexpr char kTcp1Magic[5] = "TCP1";
constexpr uint16_t kTcp1Version = 1u;
constexpr uint16_t kTcp1MsgFrame = 1u;
constexpr uint16_t kTcp1MsgResult = 2u;
constexpr uint16_t kTcp1ImageEncodingJpeg = 1u;
constexpr uint16_t kTcp1ImageWidth = 900u;
constexpr uint16_t kTcp1ImageHeight = 256u;
constexpr uint16_t kTcp1ImageChannels = 3u;
constexpr uint32_t kTcp1StateCount = 9u;
constexpr size_t kTcp1MaxPacketBytes = 16u * 1024u * 1024u;
constexpr size_t kTcp1HeaderBytes = 32u;
constexpr size_t kTcp1FramePrefixBytes = 16u;
constexpr size_t kTcp1StateBytes = 36u;

struct tcp1_header_t {
    uint16_t message_type = 0;
    uint64_t frame_id = 0;
    uint64_t timestamp_ns = 0;
    uint32_t item_count = 0;
    uint32_t payload_size = 0;
};

struct tcp1_frame_t {
    tcp1_header_t header{};
    float state[kTcp1StateCount]{};
    const uint8_t* jpeg = nullptr;
    uint32_t jpeg_size = 0;
    uint32_t jpeg_crc32 = 0;
};

static uint16_t tcp1_read_be16(const uint8_t* p) {
    return static_cast<uint16_t>(
        (static_cast<uint16_t>(p[0]) << 8U) |
        static_cast<uint16_t>(p[1]));
}

static uint32_t tcp1_read_be32(const uint8_t* p) {
    return (static_cast<uint32_t>(p[0]) << 24U) |
           (static_cast<uint32_t>(p[1]) << 16U) |
           (static_cast<uint32_t>(p[2]) << 8U) |
           static_cast<uint32_t>(p[3]);
}

static uint64_t tcp1_read_be64(const uint8_t* p) {
    return (static_cast<uint64_t>(tcp1_read_be32(p)) << 32U) |
           static_cast<uint64_t>(tcp1_read_be32(p + 4));
}

static void tcp1_write_be16(uint8_t* p, uint16_t value) {
    p[0] = static_cast<uint8_t>(value >> 8U);
    p[1] = static_cast<uint8_t>(value);
}

static void tcp1_write_be32(uint8_t* p, uint32_t value) {
    p[0] = static_cast<uint8_t>(value >> 24U);
    p[1] = static_cast<uint8_t>(value >> 16U);
    p[2] = static_cast<uint8_t>(value >> 8U);
    p[3] = static_cast<uint8_t>(value);
}

static void tcp1_write_be64(uint8_t* p, uint64_t value) {
    tcp1_write_be32(p, static_cast<uint32_t>(value >> 32U));
    tcp1_write_be32(p + 4, static_cast<uint32_t>(value));
}

static int tcp1_recv_exact(int fd, void* buffer, size_t size) {
    auto* out = static_cast<uint8_t*>(buffer);
    size_t offset = 0;

    while (offset < size) {
        const ssize_t got = recv(fd, out + offset, size - offset, 0);
        if (got == 0) {
            return 1;
        }
        if (got < 0) {
            if (errno == EINTR) {
                continue;
            }
            return -1;
        }
        offset += static_cast<size_t>(got);
    }
    return 0;
}

static int tcp1_send_all(int fd, const void* buffer, size_t size) {
    const auto* data = static_cast<const uint8_t*>(buffer);
    size_t offset = 0;

    while (offset < size) {
        const ssize_t sent =
            send(fd, data + offset, size - offset, MSG_NOSIGNAL);
        if (sent < 0) {
            if (errno == EINTR) {
                continue;
            }
            return -1;
        }
        if (sent == 0) {
            return -1;
        }
        offset += static_cast<size_t>(sent);
    }
    return 0;
}

static int tcp1_recv_packet(
    int fd,
    uint8_t** buffer,
    size_t* capacity,
    size_t* packet_size
) {
    uint8_t length_bytes[4];
    if (buffer == nullptr || capacity == nullptr || packet_size == nullptr) {
        return -1;
    }

    int rc = tcp1_recv_exact(fd, length_bytes, sizeof(length_bytes));
    if (rc != 0) {
        return rc;
    }

    const uint32_t length = tcp1_read_be32(length_bytes);
    if (length < kTcp1HeaderBytes || length > kTcp1MaxPacketBytes) {
        std::fprintf(stderr, "[TCP1] invalid packet length: %u\n", length);
        return -1;
    }

    if (*capacity < static_cast<size_t>(length)) {
        auto* resized = static_cast<uint8_t*>(
            std::realloc(*buffer, static_cast<size_t>(length)));
        if (resized == nullptr) {
            return -1;
        }
        *buffer = resized;
        *capacity = static_cast<size_t>(length);
    }

    rc = tcp1_recv_exact(fd, *buffer, static_cast<size_t>(length));
    if (rc != 0) {
        return rc;
    }

    *packet_size = static_cast<size_t>(length);
    return 0;
}

static int tcp1_send_packet(
    int fd,
    const uint8_t* packet,
    size_t packet_size
) {
    if (packet == nullptr ||
        packet_size < kTcp1HeaderBytes ||
        packet_size > kTcp1MaxPacketBytes) {
        return -1;
    }

    uint8_t length_bytes[4];
    tcp1_write_be32(length_bytes, static_cast<uint32_t>(packet_size));

    if (tcp1_send_all(fd, length_bytes, sizeof(length_bytes)) != 0) {
        return -1;
    }
    return tcp1_send_all(fd, packet, packet_size);
}

static int tcp1_parse_header(
    const uint8_t* packet,
    size_t packet_size,
    tcp1_header_t* header
) {
    if (packet == nullptr ||
        header == nullptr ||
        packet_size < kTcp1HeaderBytes) {
        return -1;
    }

    if (std::memcmp(packet, kTcp1Magic, 4) != 0) {
        std::fprintf(stderr, "[TCP1] bad magic\n");
        return -1;
    }

    if (tcp1_read_be16(packet + 4) != kTcp1Version) {
        std::fprintf(stderr, "[TCP1] unsupported version\n");
        return -1;
    }

    header->message_type = tcp1_read_be16(packet + 6);
    header->frame_id = tcp1_read_be64(packet + 8);
    header->timestamp_ns = tcp1_read_be64(packet + 16);
    header->item_count = tcp1_read_be32(packet + 24);
    header->payload_size = tcp1_read_be32(packet + 28);

    if (static_cast<size_t>(header->payload_size) !=
        packet_size - kTcp1HeaderBytes) {
        std::fprintf(stderr, "[TCP1] payload length mismatch\n");
        return -1;
    }
    return 0;
}

static int tcp1_parse_frame(
    const uint8_t* packet,
    size_t packet_size,
    tcp1_frame_t* frame
) {
    if (frame == nullptr ||
        tcp1_parse_header(packet, packet_size, &frame->header) != 0) {
        return -1;
    }

    if (frame->header.message_type != kTcp1MsgFrame ||
        frame->header.item_count != 1u) {
        std::fprintf(stderr, "[TCP1] expected one-item frame\n");
        return -1;
    }

    if (frame->header.payload_size <
        kTcp1FramePrefixBytes + kTcp1StateBytes) {
        std::fprintf(stderr, "[TCP1] truncated frame payload\n");
        return -1;
    }

    const uint8_t* prefix = packet + kTcp1HeaderBytes;

    const uint16_t width = tcp1_read_be16(prefix);
    const uint16_t height = tcp1_read_be16(prefix + 2);
    const uint16_t channels = tcp1_read_be16(prefix + 4);
    const uint16_t encoding = tcp1_read_be16(prefix + 6);

    frame->jpeg_size = tcp1_read_be32(prefix + 8);
    frame->jpeg_crc32 = tcp1_read_be32(prefix + 12);

    if (width != kTcp1ImageWidth ||
        height != kTcp1ImageHeight ||
        channels != kTcp1ImageChannels ||
        encoding != kTcp1ImageEncodingJpeg) {
        std::fprintf(stderr, "[TCP1] image contract mismatch\n");
        return -1;
    }

    if (static_cast<size_t>(frame->jpeg_size) !=
        packet_size -
            kTcp1HeaderBytes -
            kTcp1FramePrefixBytes -
            kTcp1StateBytes) {
        std::fprintf(stderr, "[TCP1] JPEG length mismatch\n");
        return -1;
    }

    const uint8_t* state_bytes = prefix + kTcp1FramePrefixBytes;
    float command_sum = 0.0f;

    for (uint32_t i = 0; i < kTcp1StateCount; ++i) {
        const uint32_t bits = tcp1_read_be32(state_bytes + i * 4u);
        std::memcpy(&frame->state[i], &bits, sizeof(bits));

        if (!std::isfinite(frame->state[i])) {
            std::fprintf(stderr, "[TCP1] state contains NaN/Inf\n");
            return -1;
        }

        if (i >= 3u) {
            const float value = frame->state[i];
            if (!(std::fabs(value) < 1.0e-6f ||
                  std::fabs(value - 1.0f) < 1.0e-6f)) {
                std::fprintf(
                    stderr,
                    "[TCP1] command state is not one-hot\n");
                return -1;
            }
            command_sum += value;
        }
    }

    if (std::fabs(command_sum - 1.0f) >= 1.0e-6f) {
        std::fprintf(
            stderr,
            "[TCP1] command state must have one active entry\n");
        return -1;
    }

    frame->jpeg = state_bytes + kTcp1StateBytes;

    if (frame->jpeg_size < 4u ||
        frame->jpeg[0] != 0xffu ||
        frame->jpeg[1] != 0xd8u ||
        frame->jpeg[frame->jpeg_size - 2u] != 0xffu ||
        frame->jpeg[frame->jpeg_size - 1u] != 0xd9u) {
        std::fprintf(stderr, "[TCP1] invalid JPEG markers\n");
        return -1;
    }

    const uint32_t actual_crc = static_cast<uint32_t>(
        crc32(0L, frame->jpeg, frame->jpeg_size));

    if (actual_crc != frame->jpeg_crc32) {
        std::fprintf(stderr, "[TCP1] JPEG CRC mismatch\n");
        return -1;
    }

    return 0;
}

static int tcp1_pack_result(
    uint8_t* packet,
    size_t capacity,
    size_t* packet_size,
    uint64_t frame_id,
    uint64_t finished_ts_ns,
    float steer,
    float throttle,
    float brake,
    double jpeg_decode_ms,
    double preprocess_ms,
    double inference_ms,
    double postprocess_ms
) {
    if (packet == nullptr ||
        packet_size == nullptr ||
        capacity <= kTcp1HeaderBytes) {
        return -1;
    }

    char* json =
        reinterpret_cast<char*>(packet + kTcp1HeaderBytes);

    const int json_size = std::snprintf(
        json,
        capacity - kTcp1HeaderBytes,
        "{\"frame_id\":%llu,\"finished_ts_ns\":%llu,"
        "\"source\":\"tcp-board-icraft\","
        "\"control\":{\"steer\":%.9g,\"throttle\":%.9g,\"brake\":%.9g},"
        "\"timing_ms\":{\"jpeg_decode\":%.6f,\"preprocess\":%.6f,"
        "\"inference\":%.6f,\"postprocess\":%.6f}}",
        static_cast<unsigned long long>(frame_id),
        static_cast<unsigned long long>(finished_ts_ns),
        static_cast<double>(steer),
        static_cast<double>(throttle),
        static_cast<double>(brake),
        jpeg_decode_ms,
        preprocess_ms,
        inference_ms,
        postprocess_ms);

    if (json_size < 0 ||
        static_cast<size_t>(json_size) >=
            capacity - kTcp1HeaderBytes) {
        return -1;
    }

    const size_t total =
        kTcp1HeaderBytes + static_cast<size_t>(json_size);

    std::memcpy(packet, kTcp1Magic, 4);
    tcp1_write_be16(packet + 4, kTcp1Version);
    tcp1_write_be16(packet + 6, kTcp1MsgResult);
    tcp1_write_be64(packet + 8, frame_id);
    tcp1_write_be64(packet + 16, finished_ts_ns);
    tcp1_write_be32(packet + 24, 3u);
    tcp1_write_be32(
        packet + 28,
        static_cast<uint32_t>(json_size));

    *packet_size = total;
    return 0;
}

